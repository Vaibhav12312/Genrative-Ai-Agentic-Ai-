"""Run the 10 eval questions against prompt v1 and v2 and write the results
table into eval/prompt_compare.md (between the RESULTS markers).

Usage (from project root, with a real provider configured in .env):
    python -m eval.run_eval
"""
import json
import re
import time
from pathlib import Path

from app.chat import run_chat
from app.config import get_settings
from app.llm import LLMError

HERE = Path(__file__).parent
QUESTIONS = json.loads((HERE / "questions.json").read_text(encoding="utf-8"))
VERSIONS = ["v1", "v2"]
START, END = "<!-- RESULTS_START -->", "<!-- RESULTS_END -->"


def words(text: str) -> int:
    return len(text.split())


def run_all() -> dict:
    results = {v: [] for v in VERSIONS}
    for q in QUESTIONS:
        for v in VERSIONS:
            t0 = time.time()
            try:
                resp, ok = run_chat(q["question"], v)
                row = {"id": q["id"], "ok": ok, "answer": resp.answer,
                       "confidence": resp.confidence, "follow_up": resp.follow_up}
            except LLMError as e:
                row = {"id": q["id"], "ok": False, "answer": f"ERROR: {e}",
                       "confidence": 0.0, "follow_up": ""}
            row["seconds"] = round(time.time() - t0, 2)
            results[v].append(row)
            print(f"Q{q['id']:>2} {v}: ok={row['ok']} conf={row['confidence']:.2f} {row['seconds']}s")
    return results


def summarise(rows: list) -> dict:
    n = len(rows)
    return {
        "valid_json": f"{sum(r['ok'] for r in rows)}/{n}",
        "avg_words": round(sum(words(r["answer"]) for r in rows) / n),
        "avg_conf": round(sum(r["confidence"] for r in rows) / n, 2),
        "has_follow_up": f"{sum(bool(r['follow_up']) for r in rows)}/{n}",
        "avg_seconds": round(sum(r["seconds"] for r in rows) / n, 2),
    }


def render(results: dict) -> str:
    s = get_settings()
    model = s.groq_model if s.provider == "groq" else s.gemini_model
    out = [f"_Generated by `python -m eval.run_eval` - provider: **{s.provider}**, model: **{model}**._", "",
           "### Automatic metrics", "",
           "| Metric | v1 (basic) | v2 (structured) |", "|---|---|---|"]
    a, b = summarise(results["v1"]), summarise(results["v2"])
    labels = [("valid_json", "Valid JSON on first parse"), ("avg_words", "Avg answer length (words)"),
              ("avg_conf", "Avg confidence"), ("has_follow_up", "Has follow_up"),
              ("avg_seconds", "Avg latency (s)")]
    for key, label in labels:
        out.append(f"| {label} | {a[key]} | {b[key]} |")
    out += ["", "### Per-question outputs", ""]
    for q in QUESTIONS:
        out.append(f"**Q{q['id']} ({q['type']}): {q['question']}**\n")
        out.append("| Version | Conf. | Answer | Follow-up |\n|---|---|---|---|")
        for v in VERSIONS:
            r = next(x for x in results[v] if x["id"] == q["id"])
            ans = r["answer"].replace("|", "/").replace("\n", " ")
            fu = r["follow_up"].replace("|", "/").replace("\n", " ")
            out.append(f"| {v} | {r['confidence']:.2f} | {ans} | {fu} |")
        out.append("")
    return "\n".join(out)


def main() -> None:
    results = run_all()
    (HERE / "results.json").write_text(json.dumps(results, indent=2, ensure_ascii=False), encoding="utf-8")
    md_path = HERE / "prompt_compare.md"
    md = md_path.read_text(encoding="utf-8")
    block = f"{START}\n{render(results)}\n{END}"
    md = re.sub(f"{re.escape(START)}.*?{re.escape(END)}", lambda _: block, md, flags=re.DOTALL)
    md_path.write_text(md, encoding="utf-8")
    print(f"\nWrote results into {md_path}")


if __name__ == "__main__":
    main()
